"""OpenPlag web UI (Streamlit).  Run:  streamlit run ui/app.py
Talks to the API over HTTP, so the UI itself needs no ML/OCR packages.

Environment
  OPENPLAG_API_URL      default http://localhost:8000
  OPENPLAG_API_KEY      must match the API's key
  OPENPLAG_UI_PASSWORD  if set, visitors must enter it (use this for ANY public deployment)
"""
import hmac
import json
import os
import time

import requests
import streamlit as st
import streamlit.components.v1 as components

API = os.environ.get("OPENPLAG_API_URL", "http://localhost:8000").rstrip("/")
KEY = os.environ.get("OPENPLAG_API_KEY", "")
PASSWORD = os.environ.get("OPENPLAG_UI_PASSWORD", "")
HEADERS = {"X-API-Key": KEY} if KEY else {}

st.set_page_config(page_title="OpenPlag", page_icon="🔎", layout="wide")


# ------------------------------------------------------------------ helpers
def api_call(method, path, **kw):
    try:
        r = requests.request(method, API + path, headers=HEADERS, timeout=kw.pop("timeout", 30), **kw)
    except requests.RequestException:
        st.error(f"Can't reach the OpenPlag API at {API}. Is it running?")
        st.stop()
    return r


def show_report(html: str):
    """The report HTML is generated by OpenPlag with every dynamic value escaped (tests cover this).
    Streamlit embeds it as-is, so never route untrusted HTML through here."""
    if hasattr(st, "iframe"):                       # newer Streamlit
        st.iframe(html, height=900)
    else:                                           # older Streamlit
        components.html(html, height=900, scrolling=True)


def show_table(rows):
    cfg = {"Link": st.column_config.LinkColumn("Link")}
    try:
        st.dataframe(rows, column_config=cfg, hide_index=True, width="stretch")
    except Exception:                               # older Streamlit
        st.dataframe(rows, column_config=cfg, hide_index=True, use_container_width=True)


def error_text(r) -> str:
    try:
        return r.json().get("detail", r.text)
    except ValueError:
        return r.text[:300]


@st.cache_data(ttl=300, show_spinner=False)
def server_config():
    r = requests.get(API + "/v1/config", headers=HEADERS, timeout=15)
    r.raise_for_status()
    return r.json()


# ------------------------------------------------------------------ optional password gate
if PASSWORD and not st.session_state.get("authed"):
    st.title("🔎 OpenPlag")
    with st.form("login"):
        pw = st.text_input("Password", type="password")
        if st.form_submit_button("Enter") and hmac.compare_digest(pw.encode(), PASSWORD.encode()):
            st.session_state["authed"] = True
            st.rerun()
        elif pw:
            st.error("Wrong password.")
    st.stop()

try:
    cfg = server_config()
except Exception:
    st.error(f"Can't reach the OpenPlag API at {API}, or the API key is wrong.")
    st.stop()

# ------------------------------------------------------------------ sidebar settings
with st.sidebar:
    st.header("Settings")
    excl_quotes = st.checkbox("Exclude quoted text", True, help="Text inside quotation marks isn't counted.")
    excl_refs = st.checkbox("Exclude bibliography", True, help="Everything after a 'References' heading is ignored.")
    excl_cites = st.checkbox("Exclude in-text citations", True, help="Markers like (Smith, 2020) or [1].")
    min_words = st.slider("Ignore matches shorter than (words)", 5, 30, cfg["defaults"]["min_match_words"])
    paraphrase = st.checkbox("Detect paraphrasing", True)
    check_ai = st.checkbox("Check for AI-generated writing", True)
    check_web = st.checkbox("Search the web & academic sources", True,
                            help="Turn off to only compare against the server's local library.")
    sources = st.multiselect("Sources to search", cfg["sources"], default=cfg["default_sources"],
                             help="CORE and Semantic Scholar need API keys set on the server.")
    st.caption(f"Reports are deleted after {cfg['retention_days']} days. Uploaded files are deleted right after reading.")

st.title("🔎 OpenPlag")
st.caption("Open-source plagiarism and AI-content checker. Results are evidence to review, not verdicts.")

tab_text, tab_file = st.tabs(["Paste text", "Upload file"])
with tab_text:
    pasted = st.text_area("Paste your text", height=260, max_chars=cfg["max_text_chars"],
                          placeholder="Paste at least a few paragraphs for meaningful results...")
with tab_file:
    exts = [e.lstrip(".") for e in cfg["allowed_extensions"]]
    uploaded = st.file_uploader(f"PDF, Word or text file (max {cfg['max_upload_mb']} MB)", type=exts)

go = st.button("Check document", type="primary")

# ------------------------------------------------------------------ submit + poll
if go:
    options = {"exclude_quotes": excl_quotes, "exclude_references": excl_refs, "exclude_citations": excl_cites,
               "min_match_words": min_words, "detect_paraphrase": paraphrase, "check_ai": check_ai,
               "check_web": check_web, "backends": sources}
    if uploaded is not None:
        r = api_call("POST", "/v1/jobs", data={"options": json.dumps(options)}, timeout=120,
                     files={"file": (uploaded.name, uploaded.getvalue())})
    elif pasted.strip():
        r = api_call("POST", "/v1/jobs", data={"text": pasted, "options": json.dumps(options)}, timeout=120)
    else:
        st.warning("Paste some text or upload a file first.")
        st.stop()
    if r.status_code != 202:
        st.error(error_text(r))
        st.stop()

    job_id = r.json()["job_id"]
    bar = st.progress(0.0, text="Queued...")
    started, job = time.time(), None
    while time.time() - started < 20 * 60:
        job = api_call("GET", f"/v1/jobs/{job_id}").json()
        bar.progress(min(1.0, float(job.get("progress") or 0)), text=job.get("stage") or "Working...")
        if job["status"] in ("done", "failed"):
            break
        time.sleep(1.5)
    bar.empty()
    if not job or job["status"] != "done":
        st.error((job or {}).get("error") or "The check took too long. Please try again.")
        st.stop()
    html = api_call("GET", f"/v1/jobs/{job_id}/report.html", timeout=60).text
    st.session_state["last"] = {"job_id": job_id, "result": job["result"], "html": html}

# ------------------------------------------------------------------ results
last = st.session_state.get("last")
if last:
    res = last["result"]
    ai = res.get("ai")
    c1, c2, c3, c4 = st.columns(4)
    c1.metric("Similarity", f"{res['similarity_percent']}%")
    c2.metric("Matched words", f"{res['matched_words']:,} / {res['eligible_words']:,}")
    c3.metric("Sources found", len(res["sources"]))
    if ai and ai.get("score") is not None:
        c4.metric("AI-writing signal", f"{ai['score']:.0%}", help=ai["label"].replace("_", " "))
    else:
        c4.metric("AI-writing signal", "n/a")
    for w in res.get("warnings", []):
        st.warning(w)
    if ai:
        st.info(f"**AI-writing signal: {ai['label'].replace('_', ' ')}** (confidence: {ai['confidence']}). {ai['caveat']}")

    t_rep, t_src, t_match, t_dl = st.tabs(["Highlighted report", "Sources", "Matches", "Download / delete"])
    with t_rep:
        show_report(last["html"])
    with t_src:
        if res["sources"]:
            show_table([{"Title": s["title"] or s["url"], "Type": s["type"], "% of document": s["percent_of_document"],
                         "Words": s["matched_words"], "Link": s["url"]} for s in res["sources"]])
        else:
            st.write("No matching sources found.")
    with t_match:
        for m in res["matches"]:
            label = "excluded (quote/citation)" if m["quoted"] else m["kind"]
            with st.expander(f"{label} - {m['similarity']:.0%} - {m['text'][:80]}..."):
                st.write(m["text"])
                st.markdown(f"Source: [{m['source_title'] or m['source_url']}]({m['highlight_url'] or m['source_url']})")
    with t_dl:
        st.download_button("Download HTML report", last["html"], "openplag-report.html", "text/html")
        st.download_button("Download JSON", json.dumps(res, indent=2), "openplag-report.json", "application/json")
        if st.button("Delete this report from the server now"):
            api_call("DELETE", f"/v1/jobs/{last['job_id']}")
            st.session_state.pop("last")
            st.success("Deleted.")
            st.rerun()
